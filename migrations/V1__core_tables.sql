-- PulseTrack V1: Core database tables
-- PostgreSQL 18.6
-- Managed by Flyway

CREATE TABLE tenants (
    tenant_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_name VARCHAR(150) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE users (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL,
    email VARCHAR(255),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT uq_users_tenant_user UNIQUE (tenant_id, user_id),
    CONSTRAINT uq_users_tenant_email UNIQUE (tenant_id, email),

    CONSTRAINT fk_users_tenant
        FOREIGN KEY (tenant_id)
        REFERENCES tenants (tenant_id)
);

CREATE TABLE sessions (
    session_id UUID PRIMARY KEY,
    tenant_id BIGINT NOT NULL,
    user_id BIGINT,
    started_at TIMESTAMPTZ NOT NULL,
    ended_at TIMESTAMPTZ,

    CONSTRAINT uq_sessions_tenant_session
        UNIQUE (tenant_id, session_id),

    CONSTRAINT chk_sessions_time
        CHECK (ended_at IS NULL OR ended_at >= started_at),

    CONSTRAINT fk_sessions_tenant
        FOREIGN KEY (tenant_id)
        REFERENCES tenants (tenant_id),

    CONSTRAINT fk_sessions_user
        FOREIGN KEY (tenant_id, user_id)
        REFERENCES users (tenant_id, user_id)
);

-- Partition events by event_time.
-- The composite primary key includes the partitioning column.
CREATE TABLE events (
    event_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    event_time TIMESTAMPTZ NOT NULL,
    tenant_id BIGINT NOT NULL,
    user_id BIGINT,
    session_id UUID,
    event_type VARCHAR(100) NOT NULL,
    properties JSONB,

    CONSTRAINT pk_events
        PRIMARY KEY (event_time, event_id),

    CONSTRAINT fk_events_tenant
        FOREIGN KEY (tenant_id)
        REFERENCES tenants (tenant_id),

    CONSTRAINT fk_events_user
        FOREIGN KEY (tenant_id, user_id)
        REFERENCES users (tenant_id, user_id),

    CONSTRAINT fk_events_session
        FOREIGN KEY (tenant_id, session_id)
        REFERENCES sessions (tenant_id, session_id)
) PARTITION BY RANGE (event_time);

-- Catch events outside explicitly created time ranges.
CREATE TABLE events_default
    PARTITION OF events DEFAULT;

CREATE TABLE products (
    product_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL,
    product_name VARCHAR(200) NOT NULL,
    current_price NUMERIC(12,2) NOT NULL,
    currency CHAR(3) NOT NULL DEFAULT 'KES',

    CONSTRAINT chk_products_price
        CHECK (current_price >= 0),

    CONSTRAINT uq_products_tenant_product
        UNIQUE (tenant_id, product_id),

    CONSTRAINT fk_products_tenant
        FOREIGN KEY (tenant_id)
        REFERENCES tenants (tenant_id)
);

CREATE TABLE orders (
    order_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    order_time TIMESTAMPTZ NOT NULL,
    order_status VARCHAR(30) NOT NULL,
    currency CHAR(3) NOT NULL DEFAULT 'KES',
    total_amount NUMERIC(12,2) NOT NULL,

    CONSTRAINT chk_orders_total
        CHECK (total_amount >= 0),

    CONSTRAINT uq_orders_tenant_order
        UNIQUE (tenant_id, order_id),

    CONSTRAINT fk_orders_tenant
        FOREIGN KEY (tenant_id)
        REFERENCES tenants (tenant_id),

    CONSTRAINT fk_orders_user
        FOREIGN KEY (tenant_id, user_id)
        REFERENCES users (tenant_id, user_id)
);

CREATE TABLE order_items (
    order_item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL,
    order_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    quantity INTEGER NOT NULL,
    unit_price NUMERIC(12,2) NOT NULL,

    CONSTRAINT chk_order_items_quantity
        CHECK (quantity > 0),

    CONSTRAINT chk_order_items_price
        CHECK (unit_price >= 0),

    CONSTRAINT fk_order_items_order
        FOREIGN KEY (tenant_id, order_id)
        REFERENCES orders (tenant_id, order_id),

    CONSTRAINT fk_order_items_product
        FOREIGN KEY (tenant_id, product_id)
        REFERENCES products (tenant_id, product_id)
);
